static bool is_vulkan(const at::Tensor& t) {
  return t.device().type() == c10::DeviceType::PrivateUse1;
}

static std::vector<int64_t> expect_ints(c10::SymIntArrayRef values) {
  std::vector<int64_t> result;
  result.reserve(values.size());
  for (const auto& value : values) {
    result.push_back(value.expect_int());
  }
  return result;
}

static bool has_vulkan_storage(const at::Tensor& t) {
  if (!is_vulkan(t)) return false;
  const uint8_t* base_ptr = reinterpret_cast<const uint8_t*>(t.storage().data_ptr().get());
  return vkc_has_buffer(base_ptr) == 1;
}

static bool has_vulkan_buffer(const at::Tensor& t) {
  return has_vulkan_storage(t) && t.storage_offset() == 0;
}

static void record_cpu_fallback(const std::string& op_name) {
  g_cpu_fallback_count.fetch_add(1, std::memory_order_relaxed);
  {
    std::lock_guard<std::mutex> lock(g_fallback_mutex);
    ++g_cpu_fallback_ops[op_name];
  }
  TORCH_CHECK(
      !g_strict_fallback,
      "Vulkan strict fallback mode rejected CPU execution for ",
      op_name);
  TORCH_WARN_ONCE(
      "pytorch-vulkan executed a CPU fallback. Inspect "
      "pytorch_vulkan.fallback_stats() and use strict_fallbacks() "
      "when validating training.");
}

// Ensure both tensors are backed by registered Vulkan storage. Kernels that
// require aligned descriptor offsets make contiguous inputs before dispatch.
static bool both_vulkan(const at::Tensor& a, const at::Tensor& b) {
  return has_vulkan_storage(a) && has_vulkan_storage(b);
}

static void check_index_bounds(
    const at::Tensor& indices,
    int64_t upper_bound,
    const char* operation) {
  TORCH_CHECK(
      indices.scalar_type() == c10::ScalarType::Long ||
          indices.scalar_type() == c10::ScalarType::Int,
      operation,
      ": indices must use int32 or int64");
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  auto check_value = [&](int64_t value) {
    TORCH_CHECK(
        value >= 0 && value < upper_bound,
        operation,
        ": index ",
        value,
        " is out of bounds for 0 <= index < ",
        upper_bound);
  };
  if (indices.is_contiguous()) {
    if (indices.scalar_type() == c10::ScalarType::Long) {
      auto* values = indices.const_data_ptr<int64_t>();
      for (const auto index : c10::irange(indices.numel())) {
        check_value(values[index]);
      }
    } else {
      auto* values = indices.const_data_ptr<int32_t>();
      for (const auto index : c10::irange(indices.numel())) {
        check_value(values[index]);
      }
    }
    return;
  }

  auto* storage = indices.storage().data_ptr().get();
  for (const auto linear_index : c10::irange(indices.numel())) {
    auto remaining = linear_index;
    auto storage_index = indices.storage_offset();
    for (int64_t dim = indices.dim() - 1; dim >= 0; --dim) {
      auto coordinate = remaining % indices.size(dim);
      remaining /= indices.size(dim);
      storage_index += coordinate * indices.stride(dim);
    }
    if (indices.scalar_type() == c10::ScalarType::Long) {
      check_value(static_cast<const int64_t*>(storage)[storage_index]);
    } else {
      check_value(static_cast<const int32_t*>(storage)[storage_index]);
    }
  }
}

