struct VulkanGuardImpl final : public c10::impl::DeviceGuardImplInterface {
  static void validate(c10::Device device) {
    TORCH_CHECK(
        device.type() == c10::DeviceType::PrivateUse1 &&
            device.index() <= 0,
        "pytorch-vulkan only supports vkgpu:0");
  }

  c10::DeviceType type() const override {
    return c10::DeviceType::PrivateUse1;
  }
  c10::Device exchangeDevice(c10::Device device) const override {
    validate(device);
    return c10::Device(c10::DeviceType::PrivateUse1, 0);
  }
  c10::Device getDevice() const override {
    return c10::Device(c10::DeviceType::PrivateUse1, 0);
  }
  void setDevice(c10::Device device) const override {
    validate(device);
  }
  void uncheckedSetDevice(c10::Device) const noexcept override {}
  c10::Stream getStream(c10::Device) const noexcept override {
    return c10::Stream(c10::Stream::DEFAULT, c10::Device(c10::DeviceType::PrivateUse1, 0));
  }
  c10::Stream getDefaultStream(c10::Device device) const override {
    validate(device);
    return c10::Stream(c10::Stream::DEFAULT, c10::Device(c10::DeviceType::PrivateUse1, 0));
  }
  c10::Stream exchangeStream(c10::Stream) const noexcept override {
    return c10::Stream(c10::Stream::DEFAULT, c10::Device(c10::DeviceType::PrivateUse1, 0));
  }
  c10::DeviceIndex deviceCount() const noexcept override {
    return 1;
  }
};

