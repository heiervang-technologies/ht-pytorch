at::Tensor cat_vulkan(const at::ITensorListRef& tensors, int64_t dim) {
  auto tensor_list = tensors.materialize();

  // Fast path: exactly 2 contiguous same-dtype tensors with registered buffers.
  if (tensor_list.size() == 2) {
    auto& a = tensor_list[0].get();
    auto& b = tensor_list[1].get();

    if (has_vulkan_buffer(a) && has_vulkan_buffer(b) &&
        a.dtype() == b.dtype() && a.is_contiguous() && b.is_contiguous()) {

      int64_t ndim = a.dim();
      if (dim < 0) dim += ndim;

      // Check all dims match except the cat dim.
      bool shapes_ok =
          dim >= 0 && dim < ndim && a.dim() == b.dim();
      for (int64_t i = 0; i < ndim && shapes_ok; i++) {
        if (i != dim) shapes_ok = (a.size(i) == b.size(i));
      }

      if (shapes_ok) {
        auto it = find_shader_for_dtype("cat2", a.scalar_type());
        if (it != g_shader_handles.end()) {
          // Compute inner sizes (product of dims after cat dim).
          int64_t inner_a = a.size(dim);
          int64_t inner_b = b.size(dim);
          for (int64_t i = dim + 1; i < ndim; i++) {
            inner_a *= a.size(i);
            inner_b *= b.size(i);
          }

          // Build output shape.
          std::vector<int64_t> out_sizes;
          for (int64_t i = 0; i < ndim; i++) {
            out_sizes.push_back(i == dim ? a.size(i) + b.size(i) : a.size(i));
          }
          auto out = at::empty(out_sizes, a.options());
          if (out.numel() == 0) {
            return out;
          }
          uint32_t num_elements = shader_numel(out, "aten::cat");
          uint32_t groups_x = shader_workgroups(num_elements);

          struct { uint32_t n, ia, ib; } pc = {
              num_elements,
              shader_u32(inner_a, "aten::cat inner size"),
              shader_u32(inner_b, "aten::cat inner size")};

          std::vector<const uint8_t*> ptrs = {
              reinterpret_cast<const uint8_t*>(a.data_ptr()),
              reinterpret_cast<const uint8_t*>(b.data_ptr()),
              reinterpret_cast<const uint8_t*>(out.data_ptr())};

          int32_t result = vkc_dispatch(
              reinterpret_cast<void*>(it->second),
              ptrs.data(), ptrs.size(),
              groups_x, 1, 1,
              reinterpret_cast<const uint8_t*>(&pc), sizeof(pc));

          if (result == 0) return out;
        }
      }
    }
  }

  // Fallback: CPU cat.
  record_cpu_fallback("aten::cat");
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  std::vector<at::Tensor> cpu_tensors;
  for (auto& t : tensor_list) {
    cpu_tensors.push_back(t.get().cpu());
  }
  auto result = at::cat(cpu_tensors, dim);
  return result.to(tensor_list[0].get().options());
}

