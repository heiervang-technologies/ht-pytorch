at::Tensor vulkan_reduction(
    const at::Tensor& self,
    const char* op_name,
    std::optional<c10::ScalarType> dtype) {
  auto shader_it = find_shader_for_dtype("sum", self.scalar_type());
  if ((!self.is_contiguous() || self.storage_offset() != 0) &&
      has_vulkan_storage(self)) {
    return vulkan_reduction(
        self.clone(at::MemoryFormat::Contiguous), op_name, dtype);
  }
  if (shader_it == g_shader_handles.end() &&
      (self.scalar_type() == c10::ScalarType::Half ||
       self.scalar_type() == c10::ScalarType::BFloat16)) {
    auto result = vulkan_reduction(
        self.to(c10::ScalarType::Float),
        op_name,
        c10::ScalarType::Float);
    return result.to(dtype.value_or(self.scalar_type()));
  }
  const bool changes_accumulation_dtype =
      dtype.has_value() && dtype.value() != self.scalar_type();
  const bool exceeds_shader_range =
      self.numel() > std::numeric_limits<uint32_t>::max();
  if (shader_it == g_shader_handles.end() || !has_vulkan_buffer(self) ||
      changes_accumulation_dtype || exceeds_shader_range) {
    record_cpu_fallback(std::string("aten::") + op_name);
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    auto self_cpu =
        at::empty(self.sizes(), self.options().device(c10::kCPU));
    std::memcpy(self_cpu.data_ptr(), self.data_ptr(), self.nbytes());
    auto r = std::strcmp(op_name, "mean") == 0
        ? at::mean(self_cpu, dtype)
        : at::sum(self_cpu, dtype);
    auto out = at::empty(r.sizes(), self.options().dtype(r.scalar_type()));
    std::memcpy(out.data_ptr(), r.data_ptr(), r.nbytes());
    return out;
  }

  auto num_elements = shader_numel(self, std::string("aten::") + op_name);
  if (num_elements == 0) {
      auto output =
          at::zeros({}, self.options().dtype(dtype.value_or(self.scalar_type())));
      if (std::strcmp(op_name, "mean") == 0) {
        scalar_inplace_vulkan(
            output,
            std::numeric_limits<float>::quiet_NaN(),
            "add_scalar");
      }
      return output;
  }

  auto current_input = self;
  uint32_t current_num = num_elements;
  bool is_mean = std::strcmp(op_name, "mean") == 0;

  // Multi-pass reduction on GPU
  while (current_num > 1) {
      // Each workgroup (256 threads) produces one partial sum.
      // Use enough workgroups to cover all elements, but cap at a reasonable
      // number to avoid excessive partial sums.
      uint32_t groups_x = std::max(
          1u,
          std::min(
              static_cast<uint32_t>(
                  (static_cast<uint64_t>(current_num) + 255) / 256),
              256u));
      std::vector<int64_t> tmp_shape = {static_cast<int64_t>(groups_x)};
      auto out = at::empty(tmp_shape, self.options());

      std::vector<const uint8_t*> ptrs = {
          reinterpret_cast<const uint8_t*>(current_input.data_ptr()),
          reinterpret_cast<const uint8_t*>(out.data_ptr())};

      ReductionPushConstants pc = {current_num};

      auto dispatch_it = find_shader_for_dtype("sum", self.scalar_type());

      int32_t result = vkc_dispatch(
          reinterpret_cast<void*>(dispatch_it->second),
          ptrs.data(), ptrs.size(),
          groups_x, 1, 1,
          reinterpret_cast<const uint8_t*>(&pc), sizeof(pc));

      TORCH_CHECK(result == 0, std::string("sum") + "_vulkan dispatch failed in multi-pass");
      current_input = out;
      current_num = groups_x;
  }

  // At this point current_input is a 1-element tensor containing the sum.
  if (is_mean && num_elements > 0) {
      // Divide by num_elements using mul.Scalar (since div.Scalar is not native yet)
      float scale = 1.0f / static_cast<float>(num_elements);
      current_input = current_input.mul(scale);
  }

  auto actual_dtype = dtype.value_or(self.scalar_type());
  return current_input.view({}).to(actual_dtype);
  }

at::Tensor vulkan_dim_reduction(
    const at::Tensor& self,
    at::OptionalIntArrayRef dim,
    bool keepdim,
    std::optional<c10::ScalarType> dtype,
    const char* op_name) {
  std::vector<int64_t> dimensions;
  if (dim.has_value() && !dim.value().empty()) {
    std::unordered_set<int64_t> unique_dimensions;
    dimensions.reserve(dim.value().size());
    for (auto dimension : dim.value()) {
      auto normalized = at::maybe_wrap_dim(dimension, self.dim(), true);
      TORCH_CHECK(
          unique_dimensions.insert(normalized).second,
          "dim ",
          dimension,
          " appears multiple times in the list of dims");
      dimensions.push_back(normalized);
    }
  } else {
    dimensions.reserve(self.dim());
    for (const auto dimension : c10::irange(self.dim())) {
      dimensions.push_back(static_cast<int64_t>(dimension));
    }
  }

  const auto base_op_name =
      std::strcmp(op_name, "mean_dim") == 0 ? "mean" : "sum";
  if (dimensions.empty() ||
      (!keepdim &&
       dimensions.size() == static_cast<size_t>(self.dim()))) {
    return vulkan_reduction(self, base_op_name, dtype);
  }
  if (self.dim() == 0) {
    return vulkan_reduction(self, base_op_name, dtype);
  }

  if (dimensions.size() > 1) {
    std::sort(dimensions.rbegin(), dimensions.rend());
    auto result = self;
    for (auto dimension : dimensions) {
      std::array<int64_t, 1> one_dimension = {dimension};
      result = vulkan_dim_reduction(
          result, one_dimension, keepdim, dtype, op_name);
    }
    return result;
  }

  std::array<int64_t, 1> normalized_dim = {dimensions[0]};
  auto it = find_shader_for_dtype(op_name, self.scalar_type());
  if ((!self.is_contiguous() || self.storage_offset() != 0) &&
      has_vulkan_storage(self)) {
    return vulkan_dim_reduction(
        self.clone(at::MemoryFormat::Contiguous),
        normalized_dim,
        keepdim,
        dtype,
        op_name);
  }
  if (it == g_shader_handles.end() &&
      (self.scalar_type() == c10::ScalarType::Half ||
       self.scalar_type() == c10::ScalarType::BFloat16)) {
    auto result = vulkan_dim_reduction(
        self.to(c10::ScalarType::Float),
        normalized_dim,
        keepdim,
        c10::ScalarType::Float,
        op_name);
    return result.to(dtype.value_or(self.scalar_type()));
  }
  const bool changes_accumulation_dtype =
      dtype.has_value() && dtype.value() != self.scalar_type();
  if (it == g_shader_handles.end() || !has_vulkan_buffer(self) ||
      changes_accumulation_dtype) {
    record_cpu_fallback(std::string("aten::") + op_name);
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    auto cpu_opts = at::TensorOptions()
                        .dtype(self.scalar_type())
                        .device(c10::kCPU);
    auto self_cpu = at::from_blob(
        const_cast<void*>(self.data_ptr()),
        self.sizes(),
        self.strides(),
        cpu_opts);
    auto r = std::strcmp(op_name, "mean_dim") == 0
        ? at::mean(self_cpu, normalized_dim, keepdim, dtype)
        : at::sum(self_cpu, normalized_dim, keepdim, dtype);
    auto out = at::empty(r.sizes(), self.options().dtype(r.scalar_type()));
    std::memcpy(out.data_ptr(), r.data_ptr(), r.nbytes());
    return out;
  }

  const int64_t d = dimensions[0];
  uint64_t outer_size_u64 = 1;
  for (int64_t index = 0; index < d; ++index) {
    outer_size_u64 *= static_cast<uint64_t>(self.size(index));
  }
  const auto reduce_size_u64 = static_cast<uint64_t>(self.size(d));
  uint64_t inner_size_u64 = 1;
  for (int64_t index = d + 1; index < self.dim(); ++index) {
    inner_size_u64 *= static_cast<uint64_t>(self.size(index));
  }
  const auto total_outputs_u64 = outer_size_u64 * inner_size_u64;
  TORCH_CHECK(
      outer_size_u64 <= std::numeric_limits<uint32_t>::max() &&
          reduce_size_u64 <= std::numeric_limits<uint32_t>::max() &&
          inner_size_u64 <= std::numeric_limits<uint32_t>::max() &&
          total_outputs_u64 <= std::numeric_limits<uint32_t>::max(),
      "aten::",
      op_name,
      " exceeds the Vulkan shader's 32-bit indexing range");
  const auto outer_size = static_cast<uint32_t>(outer_size_u64);
  const auto reduce_size = static_cast<uint32_t>(reduce_size_u64);
  const auto inner_size = static_cast<uint32_t>(inner_size_u64);
  const auto total_outputs = static_cast<uint32_t>(total_outputs_u64);
  const auto groups_x = static_cast<uint32_t>(
      (static_cast<uint64_t>(total_outputs) + 255) / 256);

  std::vector<int64_t> out_sizes;
  for (int i = 0; i < self.dim(); i++) {
      if (i == d) {
          if (keepdim) out_sizes.push_back(1);
      } else {
          out_sizes.push_back(self.size(i));
      }
  }

  auto actual_dtype = dtype.value_or(self.scalar_type());
  auto out = at::empty(out_sizes, self.options().dtype(actual_dtype));
  if (total_outputs == 0) {
    return out;
  }
  if (reduce_size == 0) {
    out.zero_();
    if (std::strcmp(op_name, "mean_dim") == 0) {
      scalar_inplace_vulkan(
          out,
          std::numeric_limits<float>::quiet_NaN(),
          "add_scalar");
    }
    return out;
  }

  std::vector<const uint8_t*> ptrs = {
      reinterpret_cast<const uint8_t*>(self.data_ptr()),
      reinterpret_cast<const uint8_t*>(out.data_ptr())};

  DimReductionPushConstants pc = {outer_size, reduce_size, inner_size};

  int32_t result = vkc_dispatch(
      reinterpret_cast<void*>(it->second),
      ptrs.data(), ptrs.size(),
      groups_x, 1, 1,
      reinterpret_cast<const uint8_t*>(&pc), sizeof(pc));

  TORCH_CHECK(result == 0, std::string(op_name) + "_vulkan dispatch failed");
  return out;
}

void vulkan_cpu_fallback(const c10::OperatorHandle& op, torch::jit::Stack* stack) {
  auto op_name = op.operator_name().name;
  if (!op.operator_name().overload_name.empty()) {
    op_name += "." + op.operator_name().overload_name;
  }
  record_cpu_fallback(op_name);
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  at::native::cpu_fallback(op, stack);
}

at::Tensor cpu_alias(const at::Tensor& tensor) {
  return at::from_blob(
      const_cast<void*>(tensor.data_ptr()),
      tensor.sizes(),
      tensor.strides(),
      at::TensorOptions().dtype(tensor.scalar_type()).device(c10::kCPU));
}

at::Tensor& scalar_inplace_vulkan(
    at::Tensor& self,
    float value,
    const char* shader_name) {
  if (self.numel() == 0) {
    return self;
  }
  auto shader = find_shader_for_dtype(shader_name, self.scalar_type());
  auto supported_dtype = self.scalar_type() == c10::ScalarType::Float ||
      self.scalar_type() == c10::ScalarType::Half ||
      self.scalar_type() == c10::ScalarType::BFloat16;
  if (supported_dtype && shader != g_shader_handles.end() &&
      has_shader_writable_layout(self)) {
    uint32_t num_elements =
        shader_numel(self, std::string("aten::") + shader_name);
    struct {
      uint32_t num_elements;
      float value;
    } push_constants{num_elements, value};
    std::vector<const uint8_t*> buffers = {
        reinterpret_cast<const uint8_t*>(self.data_ptr())};
    uint32_t shader_elements =
        self.scalar_type() == c10::ScalarType::BFloat16
        ? static_cast<uint32_t>(
              (static_cast<uint64_t>(num_elements) + 1) / 2)
        : num_elements;
    auto result = vkc_dispatch(
        reinterpret_cast<void*>(shader->second),
        buffers.data(),
        buffers.size(),
        shader_workgroups(shader_elements),
        1,
        1,
        reinterpret_cast<const uint8_t*>(&push_constants),
        sizeof(push_constants));
    TORCH_CHECK(result == 0, shader_name, " Vulkan dispatch failed");
    return self;
  }

  record_cpu_fallback(std::string("aten::") + shader_name);
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  auto alias = cpu_alias(self);
  if (std::strcmp(shader_name, "add_scalar") == 0) {
    alias.add_(value);
  } else if (std::strcmp(shader_name, "mul_scalar") == 0) {
    alias.mul_(value);
  } else if (std::strcmp(shader_name, "div_scalar") == 0) {
    alias.div_(value);
  } else {
    alias.fill_(value);
  }
  return self;
}

c10::Scalar local_scalar_dense_vulkan(const at::Tensor& self) {
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  // Host-mapped memory: just read the scalar directly.
  switch (self.scalar_type()) {
    case c10::ScalarType::Float:
      return c10::Scalar(*static_cast<float*>(self.data_ptr()));
    case c10::ScalarType::Half: {
      auto val = *static_cast<at::Half*>(self.data_ptr());
      return c10::Scalar(static_cast<float>(val));
    }
    case c10::ScalarType::Long:
      return c10::Scalar(*static_cast<int64_t*>(self.data_ptr()));
    case c10::ScalarType::Int:
      return c10::Scalar(*static_cast<int32_t*>(self.data_ptr()));
    case c10::ScalarType::Bool:
      return c10::Scalar(*static_cast<bool*>(self.data_ptr()));
    default:
      // Fallback: copy to CPU
      return self.cpu().item();
  }
}

// Autograd for SDPA: enables backward through F.scaled_dot_product_attention
// on PrivateUse1 tensors without needing the custom vulkan_sdpa wrapper.
at::Tensor sdpa_autograd_vulkan(
    const at::Tensor& query, const at::Tensor& key, const at::Tensor& value,
    const std::optional<at::Tensor>& attn_mask, double dropout_p,
    bool is_causal, std::optional<double> scale, bool enable_gqa) {

  TORCH_CHECK(
      dropout_p >= 0.0 && dropout_p <= 1.0,
      "scaled_dot_product_attention: dropout probability must be in [0, 1]");
  TORCH_CHECK(
      !is_causal || !attn_mask.has_value(),
      "scaled_dot_product_attention: an explicit mask cannot be combined "
      "with is_causal=True");
  if (dropout_p > 0.0 || enable_gqa ||
      (attn_mask.has_value() &&
       attn_mask.value().scalar_type() == c10::ScalarType::Bool)) {
    auto result = sdpa_vulkan(query, key, value, attn_mask, dropout_p, is_causal, scale, enable_gqa);
    return result;
  }

  // Use our decomposed SDPA which supports autograd natively through
  // PyTorch's built-in autograd for matmul, softmax, etc.
  float s = scale.has_value()
      ? static_cast<float>(scale.value())
      : (1.0f / std::sqrt(static_cast<float>(query.size(-1))));

  auto scores = at::matmul(query, key.transpose(-2, -1)) * s;
  if (attn_mask.has_value()) {
    scores = scores + attn_mask.value();
  }
  if (is_causal) {
    if (scores.numel() == 0) {
      scores = at::softmax(scores, -1);
      return at::matmul(scores, value);
    }
    TORCH_CHECK(
        scores.numel() <= std::numeric_limits<uint32_t>::max() &&
            scores.size(-2) <= std::numeric_limits<uint32_t>::max() &&
            scores.size(-1) <= std::numeric_limits<uint32_t>::max(),
        "causal SDPA tensor exceeds the Vulkan kernel limit");
    auto shader = find_shader_for_dtype("causal_mask", scores.scalar_type());
    if (shader == g_shader_handles.end() || !has_vulkan_buffer(scores) ||
        !scores.is_contiguous()) {
      return sdpa_vulkan(
          query,
          key,
          value,
          attn_mask,
          dropout_p,
          is_causal,
          scale,
          enable_gqa);
    }
    struct {
      uint32_t num_elements;
      uint32_t query_length;
      uint32_t key_length;
    } pc = {
        shader_numel(scores, "causal SDPA autograd mask"),
        shader_u32(
            scores.size(-2),
            "causal SDPA autograd query length"),
        shader_u32(
            scores.size(-1),
            "causal SDPA autograd key length")};
    std::vector<const uint8_t*> buffers = {
        reinterpret_cast<const uint8_t*>(scores.data_ptr())};
    auto groups = shader_workgroups(pc.num_elements);
    TORCH_CHECK(
        vkc_dispatch(
            reinterpret_cast<void*>(shader->second),
            buffers.data(),
            buffers.size(),
            groups,
            1,
            1,
            reinterpret_cast<const uint8_t*>(&pc),
            sizeof(pc)) == 0,
        "causal SDPA mask dispatch failed");
  }
  scores = at::softmax(scores, -1);
  if (!sanitize_sdpa_probabilities(scores)) {
    return sdpa_vulkan(
        query,
        key,
        value,
        attn_mask,
        dropout_p,
        is_causal,
        scale,
        enable_gqa);
  }
  return at::matmul(scores, value);
}

