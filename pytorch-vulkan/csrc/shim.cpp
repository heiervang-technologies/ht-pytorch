// --- Embedding (index into weight table) ---

at::Tensor embedding_vulkan(
    const at::Tensor& weight, const at::Tensor& indices,
    c10::SymInt padding_idx_sym, bool scale_grad_by_freq, bool sparse) {
  auto padding_idx = padding_idx_sym.expect_int();
  TORCH_CHECK(weight.dim() == 2, "embedding: weight must be 2-D");
  TORCH_CHECK(
      indices.scalar_type() == c10::ScalarType::Long ||
          indices.scalar_type() == c10::ScalarType::Int,
      "embedding: indices must be int32 or int64");
  auto out_sizes = indices.sizes().vec();
  out_sizes.push_back(weight.size(1));
  if (indices.numel() == 0 || weight.size(1) == 0) {
    return at::empty(out_sizes, weight.options());
  }
  TORCH_CHECK(
      indices.numel() <= std::numeric_limits<uint32_t>::max() &&
          weight.size(0) <= std::numeric_limits<uint32_t>::max() &&
          weight.size(1) <= std::numeric_limits<uint32_t>::max() &&
          indices.numel() <=
              std::numeric_limits<uint32_t>::max() / weight.size(1),
      "embedding: tensor is too large for the Vulkan kernel");
  auto it = find_shader_for_dtype("embedding", weight.scalar_type());
  if (it != g_shader_handles.end() && has_vulkan_buffer(weight) &&
      has_vulkan_buffer(indices) && weight.is_contiguous() &&
      indices.is_contiguous()) {
    check_index_bounds(indices, weight.size(0), "embedding");
    uint32_t num_indices =
        shader_numel(indices, "aten::embedding indices");
    uint32_t embedding_dim =
        shader_u32(weight.size(1), "aten::embedding dimension");
    uint32_t total_elements = num_indices * embedding_dim;

    auto out = at::empty(out_sizes, weight.options());

    struct {
      uint32_t num_indices;
      uint32_t embedding_dim;
      uint32_t num_weights;
      uint32_t index_words;
    } pc = {
        num_indices,
        embedding_dim,
        shader_u32(weight.size(0), "aten::embedding rows"),
        indices.scalar_type() == c10::ScalarType::Long ? 2U : 1U};

    std::vector<const uint8_t*> ptrs = {
        reinterpret_cast<const uint8_t*>(weight.data_ptr()),
        reinterpret_cast<const uint8_t*>(indices.data_ptr()),
        reinterpret_cast<const uint8_t*>(out.data_ptr())};

    uint32_t groups_x = shader_workgroups(total_elements);
    int32_t result = vkc_dispatch(
        reinterpret_cast<void*>(it->second),
        ptrs.data(), ptrs.size(),
        groups_x, 1, 1,
        reinterpret_cast<const uint8_t*>(&pc), sizeof(pc));

    if (result == 0) return out;
  }

  // Fallback: CPU embedding
  record_cpu_fallback("aten::embedding");
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  auto result_cpu = at::embedding(
      weight.cpu(),
      indices.cpu(),
      padding_idx,
      scale_grad_by_freq,
      sparse);
  return result_cpu.to(
      weight.options().dtype(result_cpu.scalar_type()));
}

at::Tensor embedding_dense_backward_vulkan(
    const at::Tensor& grad_output, const at::Tensor& indices,
    c10::SymInt num_weights_sym, c10::SymInt padding_idx_sym,
    bool scale_grad_by_freq) {
  auto num_weights = num_weights_sym.expect_int();
  auto padding_idx = padding_idx_sym.expect_int();
  TORCH_CHECK(num_weights >= 0, "embedding_dense_backward: num_weights must be non-negative");
  TORCH_CHECK(
      indices.scalar_type() == c10::ScalarType::Long ||
          indices.scalar_type() == c10::ScalarType::Int,
      "embedding_dense_backward: indices must be int32 or int64");
  TORCH_CHECK(
      grad_output.dim() >= 1 && grad_output.size(-1) >= 0,
      "embedding_dense_backward: invalid grad_output shape");
  auto embedding_dim = grad_output.size(-1);
  TORCH_CHECK(
      indices.numel() <= std::numeric_limits<uint32_t>::max() &&
          num_weights <= std::numeric_limits<uint32_t>::max() &&
          embedding_dim <= std::numeric_limits<uint32_t>::max() &&
          (embedding_dim == 0 ||
           num_weights <=
               std::numeric_limits<uint32_t>::max() / embedding_dim) &&
          padding_idx >= std::numeric_limits<int32_t>::min() &&
          padding_idx <= std::numeric_limits<int32_t>::max(),
      "embedding_dense_backward: tensor is too large for the Vulkan kernel");
  auto output = at::empty(
      {num_weights, embedding_dim},
      grad_output.options(),
      c10::MemoryFormat::Contiguous);
  if (output.numel() == 0) {
    return output;
  }

  auto shader = find_shader_for_dtype(
      "embedding_backward", grad_output.scalar_type());
  if (shader != g_shader_handles.end() &&
      has_vulkan_buffer(grad_output) &&
      has_vulkan_buffer(indices) &&
      grad_output.is_contiguous() &&
      indices.is_contiguous() &&
      indices.numel() == grad_output.numel() / embedding_dim) {
    check_index_bounds(indices, num_weights, "embedding_dense_backward");
    struct {
      uint32_t num_indices;
      uint32_t num_weights;
      uint32_t embedding_dim;
      int32_t padding_idx;
      uint32_t scale_grad_by_freq;
      uint32_t index_words;
    } pc = {
        shader_numel(
            indices,
            "aten::embedding_dense_backward indices"),
        shader_u32(
            num_weights,
            "aten::embedding_dense_backward rows"),
        shader_u32(
            embedding_dim,
            "aten::embedding_dense_backward dimension"),
        static_cast<int32_t>(padding_idx),
        scale_grad_by_freq ? 1U : 0U,
        indices.scalar_type() == c10::ScalarType::Long ? 2U : 1U};
    std::vector<const uint8_t*> ptrs = {
        reinterpret_cast<const uint8_t*>(grad_output.data_ptr()),
        reinterpret_cast<const uint8_t*>(indices.data_ptr()),
        reinterpret_cast<const uint8_t*>(output.data_ptr())};
    auto groups = shader_workgroups(
        shader_numel(output, "aten::embedding_dense_backward"));
    if (vkc_dispatch(
            reinterpret_cast<void*>(shader->second),
            ptrs.data(),
            ptrs.size(),
            groups,
            1,
            1,
            reinterpret_cast<const uint8_t*>(&pc),
            sizeof(pc)) == 0) {
      return output;
    }
  }

  record_cpu_fallback("aten::embedding_dense_backward");
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  auto grad_cpu = grad_output.to(c10::kCPU);
  auto indices_cpu = indices.to(c10::kCPU);
  auto result_cpu = at::embedding_dense_backward(grad_cpu, indices_cpu, num_weights, padding_idx, scale_grad_by_freq);
  return result_cpu.to(grad_output.device());
}

at::Tensor one_hot_vulkan(const at::Tensor& self, int64_t num_classes) {
  TORCH_CHECK(
      self.scalar_type() == c10::ScalarType::Long,
      "one_hot is only applicable to index tensor of type LongTensor");
  if (num_classes == -1) {
    record_cpu_fallback("aten::one_hot.dynamic_num_classes");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    return at::one_hot(self.cpu(), num_classes).to(self.options());
  }
  TORCH_CHECK(num_classes >= 1, "num_classes should be positive");
  TORCH_CHECK(
      num_classes <= std::numeric_limits<uint32_t>::max(),
      "one_hot: num_classes exceeds the Vulkan kernel limit");
  auto shape = self.sizes().vec();
  shape.push_back(num_classes);
  TORCH_CHECK(
      self.numel() <=
          std::numeric_limits<uint32_t>::max() / num_classes,
      "one_hot: output is too large for the Vulkan kernel");
  auto output_numel = self.numel() * num_classes;
  auto output = at::empty(shape, self.options());
  if (self.numel() == 0) {
    return output;
  }
  TORCH_CHECK(
      self.dim() <= 4 &&
          self.numel() <= std::numeric_limits<uint32_t>::max() &&
          self.storage_offset() >= 0 &&
          self.storage_offset() <= std::numeric_limits<uint32_t>::max(),
      "one_hot: tensor is too large for the Vulkan kernel");
  auto shader = g_shader_handles.find("one_hot");
  if (shader == g_shader_handles.end() || !has_vulkan_storage(self)) {
    record_cpu_fallback("aten::one_hot");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    return at::one_hot(self.cpu(), num_classes).to(self.options());
  }
  check_index_bounds(self, num_classes, "one_hot");

  struct {
    uint32_t num_elements;
    uint32_t num_classes;
    uint32_t ndim;
    uint32_t size0;
    uint32_t size1;
    uint32_t size2;
    uint32_t size3;
    uint32_t stride0;
    uint32_t stride1;
    uint32_t stride2;
    uint32_t stride3;
    uint32_t storage_offset;
  } pc = {
      shader_numel(self, "aten::one_hot input"),
      shader_u32(num_classes, "aten::one_hot classes"),
      shader_u32(self.dim(), "aten::one_hot rank"),
      1, 1, 1, 1,
      0, 0, 0, 0,
      static_cast<uint32_t>(self.storage_offset())};
  auto padded_dimension = 4 - self.dim();
  auto* sizes = &pc.size0;
  auto* strides = &pc.stride0;
  for (int64_t dim = 0; dim < self.dim(); ++dim) {
    TORCH_CHECK(
        self.size(dim) <= std::numeric_limits<uint32_t>::max() &&
            self.stride(dim) >= 0 &&
            self.stride(dim) <= std::numeric_limits<uint32_t>::max(),
        "one_hot: tensor metadata exceeds the Vulkan kernel limit");
    sizes[padded_dimension + dim] =
        shader_u32(self.size(dim), "aten::one_hot dimension");
    strides[padded_dimension + dim] =
        shader_u32(self.stride(dim), "aten::one_hot stride");
  }
  std::vector<const uint8_t*> buffers = {
      reinterpret_cast<const uint8_t*>(self.storage().data_ptr().get()),
      reinterpret_cast<const uint8_t*>(output.data_ptr())};
  auto groups = shader_workgroups(
      shader_u32(output_numel, "aten::one_hot output"));
  TORCH_CHECK(
      vkc_dispatch(
          reinterpret_cast<void*>(shader->second),
          buffers.data(),
          buffers.size(),
          groups,
          1,
          1,
          reinterpret_cast<const uint8_t*>(&pc),
          sizeof(pc)) == 0,
      "one_hot Vulkan dispatch failed");
  return output;
}

// --- Shape/stride metadata ops (zero-copy) ---

at::Tensor make_vulkan_alias(
    const at::Tensor& self,
    c10::IntArrayRef size,
    c10::IntArrayRef stride,
    int64_t storage_offset) {
  auto implementation =
      self.unsafeGetTensorImpl()->shallow_copy_and_detach(
          self.unsafeGetTensorImpl()->version_counter(),
          /*allow_tensor_metadata_change=*/true);
  implementation->set_autograd_meta(nullptr);
  implementation->set_storage_offset(storage_offset);
  implementation->set_sizes_and_strides(size, stride);
  return at::Tensor(std::move(implementation));
}

at::Tensor view_vulkan(const at::Tensor& self, at::SymIntArrayRef size) {
  // Resolve symbolic ints to concrete values.
  std::vector<int64_t> concrete_size;
  for (const auto& s : size) {
    concrete_size.push_back(s.expect_int());
  }
  auto inferred = at::infer_size_dv(concrete_size, self.numel());
  auto strides = at::detail::computeStride(self.sizes(), self.strides(), inferred);
  TORCH_CHECK(strides.has_value(),
              "view size is not compatible with input tensor's size and stride");
  return make_vulkan_alias(
      self, inferred, strides.value(), self.storage_offset());
}

at::Tensor _reshape_alias_vulkan(
    const at::Tensor& self, c10::SymIntArrayRef size_sym,
    c10::SymIntArrayRef stride_sym) {
  auto size_values = expect_ints(size_sym);
  auto stride_values = expect_ints(stride_sym);
  return make_vulkan_alias(
      self, size_values, stride_values, self.storage_offset());
}

at::Tensor expand_vulkan(
    const at::Tensor& self,
    c10::SymIntArrayRef size_sym,
    bool implicit) {
  auto size_values = expect_ints(size_sym);
  auto expanded = at::inferExpandGeometry_dimvector(
      self.sizes(), self.strides(), size_values);
  auto result = self.as_strided(
      expanded.sizes,
      expanded.strides,
      self.storage_offset());
  return result;
}

at::Tensor as_strided_vulkan(
    const at::Tensor& self, c10::SymIntArrayRef size_sym,
    c10::SymIntArrayRef stride_sym,
    std::optional<c10::SymInt> storage_offset_sym) {
  auto size_values = expect_ints(size_sym);
  auto stride_values = expect_ints(stride_sym);
  c10::IntArrayRef size(size_values);
  c10::IntArrayRef stride(stride_values);
  auto offset = storage_offset_sym.has_value()
      ? storage_offset_sym.value().expect_int()
      : self.storage_offset();
  at::native::checkInBoundsForStorage(
      size,
      stride,
      offset,
      self.dtype(),
      self.storage());
  return make_vulkan_alias(self, size, stride, offset);
}

at::Tensor detach_vulkan(const at::Tensor& self) {
  auto implementation =
      self.unsafeGetTensorImpl()->shallow_copy_and_detach(
          self.unsafeGetTensorImpl()->version_counter(),
          /*allow_tensor_metadata_change=*/false);
  implementation->set_autograd_meta(nullptr);
  return at::Tensor(std::move(implementation));
}

at::Tensor _to_copy_vulkan(
    const at::Tensor& self,
    std::optional<c10::ScalarType> dtype,
    std::optional<c10::Layout> layout,
    std::optional<c10::Device> device,
    std::optional<bool> pin_memory,
    bool non_blocking,
    std::optional<c10::MemoryFormat> memory_format) {
  auto target_dtype = dtype.value_or(self.scalar_type());
  auto target_device = device.value_or(self.device());

  if (target_device.type() == c10::DeviceType::CPU) {
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    // Vulkan -> CPU: use from_blob to avoid recursive dispatch.
    auto result = at::empty(self.sizes(), self.options().device(c10::kCPU).dtype(target_dtype));
    if (self.is_contiguous() && result.is_contiguous() &&
        self.scalar_type() == target_dtype) {
      std::memcpy(result.data_ptr(), self.data_ptr(), self.nbytes());
    } else {
      auto src_cpu = at::from_blob(
          const_cast<void*>(self.data_ptr()), self.sizes(), self.strides(),
          at::TensorOptions().dtype(self.scalar_type()).device(c10::kCPU));
      result.copy_(src_cpu, non_blocking);
    }
    return result;
  }

  at::Tensor result;
  if (memory_format == c10::MemoryFormat::Preserve) {
    result = at::empty_strided(
        self.sizes(),
        self.strides(),
        self.options().device(target_device).dtype(target_dtype));
  } else {
    result = at::empty(
        self.sizes(),
        self.options().device(target_device).dtype(target_dtype),
        memory_format);
  }
  copy_vulkan_(result, self, non_blocking);
  return result;
}

const at::Tensor& resize_vulkan_(
    const at::Tensor& self,
    c10::SymIntArrayRef size_sym,
    std::optional<c10::MemoryFormat> optional_memory_format) {
  auto size_values = expect_ints(size_sym);
  c10::IntArrayRef size(size_values);
  at::detail::check_size_nonnegative(size);
  TORCH_CHECK(
      !optional_memory_format.has_value() ||
          optional_memory_format == c10::MemoryFormat::Contiguous ||
          optional_memory_format == c10::MemoryFormat::Preserve,
      "Vulkan resize_ only supports contiguous memory format");
  auto* self_impl = self.unsafeGetTensorImpl();
  auto new_size_bytes = at::detail::computeStorageNbytesContiguous(
      size,
      self_impl->dtype().itemsize());

  if (new_size_bytes > self_impl->storage().nbytes()) {
    TORCH_CHECK(vkc_flush() == 0, "Vulkan resize_: synchronization failed");
    at::native::resize_bytes_cpu(
        self_impl->storage().unsafeGetStorageImpl(),
        static_cast<size_t>(new_size_bytes));
  }

  self_impl->set_sizes_contiguous(size);
  return self;
}

at::Tensor _copy_from_and_resize_vulkan(const at::Tensor& self, const at::Tensor& dst) {
  TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
  if (dst.sizes() != self.sizes()) {
    resize_vulkan_(dst, self.sym_sizes(), std::nullopt);
  }
  dst.copy_(self);
  return dst;
}

#pragma pack(push, 1)
struct AddcdivPushConstants {
    uint32_t num_elements;
    float value;
};
#pragma pack(pop)

at::Tensor addcdiv_vulkan(const at::Tensor& self, const at::Tensor& tensor1, const at::Tensor& tensor2, const at::Scalar& value) {
  auto it = find_shader_for_dtype("addcdiv", self.scalar_type());
  if (it == g_shader_handles.end() || !has_vulkan_buffer(self) ||
      !has_vulkan_buffer(tensor1) || !has_vulkan_buffer(tensor2) ||
      self.scalar_type() != tensor1.scalar_type() ||
      self.scalar_type() != tensor2.scalar_type()) {
    record_cpu_fallback("aten::addcdiv");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    return at::addcdiv(self.cpu(), tensor1.cpu(), tensor2.cpu(), value).to(self.options());
  }

  auto [t1_b, t2_b] = needs_broadcast(tensor1, tensor2)
      ? broadcast_operands(tensor1, tensor2)
      : std::make_pair(
            contiguous_vulkan_input(tensor1),
            contiguous_vulkan_input(tensor2));
  auto self_pair = needs_broadcast(self, t1_b)
      ? broadcast_operands(self, t1_b)
      : std::make_pair(contiguous_vulkan_input(self), t1_b);
  auto self_b = std::move(self_pair.first);

  auto out = at::empty_like(self_b);
  auto final_t1 =
      contiguous_vulkan_input(t1_b.expand(self_b.sizes()));
  auto final_t2 =
      contiguous_vulkan_input(t2_b.expand(self_b.sizes()));
  if (out.numel() == 0) {
    return out;
  }
  uint32_t num_elements =
      shader_numel(self_b, "aten::addcdiv");
  uint32_t groups_x = shader_workgroups(num_elements);

  std::vector<const uint8_t*> ptrs = {
      reinterpret_cast<const uint8_t*>(self_b.data_ptr()),
      reinterpret_cast<const uint8_t*>(final_t1.data_ptr()),
      reinterpret_cast<const uint8_t*>(final_t2.data_ptr()),
      reinterpret_cast<const uint8_t*>(out.data_ptr())};

  AddcdivPushConstants pc = {num_elements, value.toFloat()};

  int32_t result = vkc_dispatch(
      reinterpret_cast<void*>(it->second),
      ptrs.data(), ptrs.size(),
      groups_x, 1, 1,
      reinterpret_cast<const uint8_t*>(&pc), sizeof(pc));

  TORCH_CHECK(result == 0, "addcdiv_vulkan dispatch failed");
  return out;
}

