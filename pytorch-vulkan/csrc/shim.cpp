class ShaderHandleRegistry {
 public:
  struct EndSentinel {};

  class ReadHandle {
   public:
    ReadHandle(
        std::recursive_mutex& mutex,
        const std::unordered_map<std::string, int64_t>& handles,
        const std::string& name)
        : lock_(mutex), iterator_(handles.find(name)), end_(handles.end()) {}

    ReadHandle(ReadHandle&&) = default;
    ReadHandle& operator=(ReadHandle&&) = default;
    ReadHandle(const ReadHandle&) = delete;
    ReadHandle& operator=(const ReadHandle&) = delete;

    const std::pair<const std::string, int64_t>* operator->() const {
      return &*iterator_;
    }

    bool operator==(EndSentinel) const {
      return iterator_ == end_;
    }

    bool operator!=(EndSentinel sentinel) const {
      return !(*this == sentinel);
    }

   private:
    std::unique_lock<std::recursive_mutex> lock_;
    std::unordered_map<std::string, int64_t>::const_iterator iterator_;
    std::unordered_map<std::string, int64_t>::const_iterator end_;
  };

  ReadHandle find(const std::string& name) const {
    return ReadHandle(mutex_, handles_, name);
  }

  EndSentinel end() const {
    return {};
  }

  void set(const std::string& name, int64_t handle) {
    std::lock_guard<std::recursive_mutex> lock(mutex_);
    handles_[name] = handle;
  }

  void clear() {
    std::lock_guard<std::recursive_mutex> lock(mutex_);
    handles_.clear();
  }

  void erase_handle(int64_t handle) {
    std::lock_guard<std::recursive_mutex> lock(mutex_);
    erase_handle_unlocked(handle);
  }

  bool destroy_all() {
    std::lock_guard<std::recursive_mutex> lock(mutex_);
    while (!handles_.empty()) {
      const auto handle = handles_.begin()->second;
      if (vkc_destroy_shader(reinterpret_cast<void*>(handle)) != 0) {
        return false;
      }
      erase_handle_unlocked(handle);
    }
    return true;
  }

 private:
  void erase_handle_unlocked(int64_t handle) {
    for (auto iterator = handles_.begin(); iterator != handles_.end();) {
      if (iterator->second == handle) {
        iterator = handles_.erase(iterator);
      } else {
        ++iterator;
      }
    }
  }

  mutable std::recursive_mutex mutex_;
  std::unordered_map<std::string, int64_t> handles_;
};

