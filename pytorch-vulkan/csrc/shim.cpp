// Expand operands to a common broadcast shape and make them contiguous.
// Returns false if broadcasting is not needed (shapes already match).
static bool needs_broadcast(const at::Tensor& a, const at::Tensor& b) {
  return a.sizes() != b.sizes();
}

static at::Tensor contiguous_vulkan_input(const at::Tensor& tensor) {
  if (tensor.is_contiguous() && tensor.storage_offset() == 0) {
    return tensor;
  }
  return tensor.clone(at::MemoryFormat::Contiguous);
}

static bool has_shader_writable_layout(const at::Tensor& tensor) {
  return has_vulkan_buffer(tensor) &&
      tensor.is_contiguous() &&
      tensor.storage_offset() == 0;
}

static uint32_t shader_u32(int64_t value, std::string_view field) {
  TORCH_CHECK(
      value >= 0 &&
          static_cast<uint64_t>(value) <=
              std::numeric_limits<uint32_t>::max(),
      field,
      " exceeds the Vulkan shader's 32-bit indexing range");
  return static_cast<uint32_t>(value);
}

static uint32_t shader_numel(
    const at::Tensor& tensor,
    std::string_view op_name) {
  return shader_u32(tensor.numel(), op_name);
}

static uint32_t shader_workgroups(
    uint32_t num_elements,
    uint32_t local_size = 256) {
  TORCH_INTERNAL_ASSERT(num_elements > 0 && local_size > 0);
  return static_cast<uint32_t>(
      (static_cast<uint64_t>(num_elements) + local_size - 1) /
      local_size);
}

static std::pair<at::Tensor, at::Tensor> broadcast_operands(
    const at::Tensor& a, const at::Tensor& b) {
  auto shape = at::infer_size(a.sizes(), b.sizes());
  return {
      contiguous_vulkan_input(a.expand(shape)),
      contiguous_vulkan_input(b.expand(shape))};
}

// Select the right shader for dtype (f32 or f16 variant).
static ShaderHandleRegistry::ReadHandle
find_shader_for_dtype(const std::string& base_name, c10::ScalarType dtype) {
  if (dtype == c10::ScalarType::Half) {
    return g_shader_handles.find(base_name + "_f16");
  } else if (dtype == c10::ScalarType::BFloat16) {
    return g_shader_handles.find(base_name + "_bf16");
  } else if (dtype != c10::ScalarType::Float) {
    return g_shader_handles.find("");
  }
  return g_shader_handles.find(base_name);
}

at::Tensor add_vulkan(const at::Tensor& self, const at::Tensor& other, const at::Scalar& alpha) {
  auto it = find_shader_for_dtype("add", self.scalar_type());
  if (it == g_shader_handles.end() ||
      self.scalar_type() != other.scalar_type() ||
      !both_vulkan(self, other)) {
    record_cpu_fallback("aten::add.Tensor");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    auto result = at::add(self.cpu(), other.cpu(), alpha);
    return result.to(self.options().dtype(result.scalar_type()));
  }
  if (self.numel() == 0 || other.numel() == 0) {
    auto shape = at::infer_size(self.sizes(), other.sizes());
    return at::empty(shape, self.options());
  }

  auto [a, b] = needs_broadcast(self, other)
      ? broadcast_operands(self, other)
      : std::make_pair(
            contiguous_vulkan_input(self),
            contiguous_vulkan_input(other));
  if (alpha.toFloat() != 1.0f) {
    b = b.clone();
    scalar_inplace_vulkan(b, alpha.toFloat(), "mul_scalar");
  }
  auto out = at::empty_like(a);
  uint32_t num_elements = shader_numel(a, "aten::add.Tensor");
  uint32_t groups_x = shader_workgroups(num_elements);

  std::vector<const uint8_t*> ptrs = {
      reinterpret_cast<const uint8_t*>(a.data_ptr()),
      reinterpret_cast<const uint8_t*>(b.data_ptr()),
      reinterpret_cast<const uint8_t*>(out.data_ptr())};

  std::string pc_data;
  pc_data.resize(sizeof(uint32_t));
  std::memcpy(pc_data.data(), &num_elements, sizeof(uint32_t));

  int32_t result = vkc_dispatch(
      reinterpret_cast<void*>(it->second),
      ptrs.data(), ptrs.size(),
      groups_x, 1, 1,
      reinterpret_cast<const uint8_t*>(pc_data.data()), pc_data.size());

  TORCH_CHECK(result == 0, "add_vulkan dispatch failed");
  return out;
}

at::Tensor& add__vulkan(at::Tensor& self, const at::Tensor& other, const at::Scalar& alpha) {
  if (self.numel() == 0) {
    at::infer_size(self.sizes(), other.sizes());
    return self;
  }
  auto it = find_shader_for_dtype("add", self.scalar_type());
  if (it == g_shader_handles.end() ||
      self.scalar_type() != other.scalar_type() ||
      !both_vulkan(self, other) ||
      !has_shader_writable_layout(self)) {
    record_cpu_fallback("aten::add_.Tensor");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    auto self_cpu = at::from_blob(self.data_ptr(), self.sizes(), self.strides(), at::TensorOptions().dtype(self.scalar_type()).device(c10::kCPU));
    self_cpu.add_(other.cpu(), alpha);
    return self;
  }

  auto b = contiguous_vulkan_input(other.expand(self.sizes()));
  if (alpha.toFloat() != 1.0f) {
    b = b.clone();
    scalar_inplace_vulkan(b, alpha.toFloat(), "mul_scalar");
  }
  uint32_t num_elements = shader_numel(self, "aten::add_.Tensor");
  uint32_t groups_x = shader_workgroups(num_elements);

  std::vector<const uint8_t*> ptrs = {
      reinterpret_cast<const uint8_t*>(self.data_ptr()),
      reinterpret_cast<const uint8_t*>(b.data_ptr()),
      reinterpret_cast<const uint8_t*>(self.data_ptr())};

  std::string pc_data;
  pc_data.resize(sizeof(uint32_t));
  std::memcpy(pc_data.data(), &num_elements, sizeof(uint32_t));

  int32_t result = vkc_dispatch(
      reinterpret_cast<void*>(it->second),
      ptrs.data(), ptrs.size(),
      groups_x, 1, 1,
      reinterpret_cast<const uint8_t*>(pc_data.data()), pc_data.size());

  TORCH_CHECK(result == 0, "add__vulkan dispatch failed");
  return self;
}

at::Tensor& add_out_vulkan(const at::Tensor& self, const at::Tensor& other, const at::Scalar& alpha, at::Tensor& out) {
  auto shape = at::infer_size(self.sizes(), other.sizes());
  at::native::resize_output(out, shape);
  if (out.numel() == 0) {
    return out;
  }
  auto it = find_shader_for_dtype("add", self.scalar_type());
  if (it == g_shader_handles.end() ||
      self.scalar_type() != other.scalar_type() ||
      self.scalar_type() != out.scalar_type() ||
      !both_vulkan(self, other) || !has_vulkan_buffer(out) ||
      !out.is_contiguous()) {
    record_cpu_fallback("aten::add.out");
    TORCH_CHECK(vkc_flush() == 0, "Vulkan synchronization failed");
    auto self_cpu = at::from_blob(const_cast<void*>(self.data_ptr()), self.sizes(), self.strides(), at::TensorOptions().dtype(self.scalar_type()).device(c10::kCPU));
    auto other_cpu = at::from_blob(const_cast<void*>(other.data_ptr()), other.sizes(), other.strides(), at::TensorOptions().dtype(other.scalar_type()).device(c10::kCPU));
    auto out_cpu = at::from_blob(out.data_ptr(), out.sizes(), out.strides(), at::TensorOptions().dtype(out.scalar_type()).device(c10::kCPU));
    at::add_out(out_cpu, self_cpu, other_cpu, alpha);
    return out;
  }

  auto [a, b] = needs_broadcast(self, other)
      ? broadcast_operands(self, other)
      : std::make_pair(
            contiguous_vulkan_input(self),
            contiguous_vulkan_input(other));
  if (alpha.toFloat() != 1.0f) {
    b = b.clone();
    scalar_inplace_vulkan(b, alpha.toFloat(), "mul_scalar");
  }

  uint32_t num_elements = shader_numel(a, "aten::add.out");
  uint32_t groups_x = shader_workgroups(num_elements);

  std::vector<const uint8_t*> ptrs = {
      reinterpret_cast<const uint8_t*>(a.data_ptr()),
      reinterpret_cast<const uint8_t*>(b.data_ptr()),
      reinterpret_cast<const uint8_t*>(out.data_ptr())};

  std::string pc_data;
  pc_data.resize(sizeof(uint32_t));
  std::memcpy(pc_data.data(), &num_elements, sizeof(uint32_t));

  int32_t result = vkc_dispatch(
      reinterpret_cast<void*>(it->second),
      ptrs.data(), ptrs.size(),
      groups_x, 1, 1,
      reinterpret_cast<const uint8_t*>(pc_data.data()), pc_data.size());

  TORCH_CHECK(result == 0, "add_out_vulkan dispatch failed");
  return out;
}

