struct RustVulkanAllocator final : public c10::Allocator {
  c10::DataPtr allocate(size_t n) override {
    if (n == 0) {
      return {nullptr, nullptr, &raw_delete, c10::Device(c10::DeviceType::PrivateUse1, 0)};
    }
    void* handle = nullptr;
    uint8_t* ptr = vkc_alloc(n, &handle);
    if (!ptr) {
      throw std::runtime_error("Vulkan allocation failed for " + std::to_string(n) + " bytes");
    }
    return {ptr, handle, &raw_delete, c10::Device(c10::DeviceType::PrivateUse1, 0)};
  }

  c10::DeleterFnPtr raw_deleter() const override {
    return &raw_delete;
  }

  void copy_data(void* dest, const void* src, std::size_t count) const override {
    std::memcpy(dest, src, count);
  }

  static void raw_delete(void* ctx) {
    if (ctx) {
      vkc_free(ctx);
    }
  }
};

